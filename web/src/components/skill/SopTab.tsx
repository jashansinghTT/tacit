import ReactMarkdown from 'react-markdown'
import remarkGfm from 'remark-gfm'
import { Download, FileText, Printer } from 'lucide-react'
import type { Skill } from '@/lib/api'
import { fmtDate, fmtScorePct } from '@/lib/format'
import { Button, Panel } from '@/components/ui'

function download(name: string, text: string, type = 'text/markdown') {
  const url = URL.createObjectURL(new Blob([text], { type }))
  const a = document.createElement('a')
  a.href = url
  a.download = name
  a.click()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

function slug(s: string) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

/** Standard work (SOP) generated from the capture, rendered, with export. */
export function SopTab({ skill }: { skill: Skill }) {
  return (
    <div className="grid gap-4 xl:grid-cols-[minmax(0,8fr)_minmax(0,4fr)]">
      <Panel
        title="Standard work"
        eyebrow="generated by gpt-oss-20b on chip 2 from the capture"
        actions={
          <>
            <Button size="sm" variant="ghost" icon={<Printer className="size-3.5" />} onClick={() => window.print()}>
              Print
            </Button>
            <Button size="sm" variant="secondary" icon={<Download className="size-3.5" />} onClick={() => download(`${slug(skill.title)}-sop.md`, skill.sop_markdown)} data-testid="sop-export">
              Export .md
            </Button>
          </>
        }
        data-testid="sop-panel"
      >
        <article className="prose-tacit mx-auto max-w-3xl py-4">
          <ReactMarkdown remarkPlugins={[remarkGfm]}>{skill.sop_markdown || '_No SOP yet._'}</ReactMarkdown>
        </article>
      </Panel>
      <aside className="space-y-4">
        <Panel title="Illustrations">
          <div className="grid grid-cols-2 gap-2">
            {skill.steps.map((s) => (
              <figure key={s.id} className="overflow-hidden rounded-md bg-ink-950 shadow-[inset_0_0_0_1px_var(--color-line)]">
                {s.keyframe && <img src={s.keyframe} alt={s.title} loading="lazy" className="aspect-video w-full object-cover" />}
                <figcaption className="truncate px-2 py-1.5 text-[11px] text-fg-subtle">
                  <span className="telemetry mr-1 text-ion">{s.index}</span>
                  {s.title}
                </figcaption>
              </figure>
            ))}
          </div>
        </Panel>
        <Panel title="Document">
          <dl className="space-y-2 text-[13px]">
            {[
              ['Skill', skill.title],
              ['Expert', skill.expert.name],
              ['Captured', fmtDate(skill.created_at)],
              ['Steps', String(skill.steps.length)],
              ['Verification', skill.verification.status === 'verified' ? `Verified, ${fmtScorePct(skill.verification.score)}` : skill.verification.status],
            ].map(([k, v]) => (
              <div key={k} className="flex justify-between gap-3">
                <dt className="text-fg-subtle">{k}</dt>
                <dd className="text-right text-fg-muted">{v}</dd>
              </div>
            ))}
          </dl>
          <p className="mt-4 flex gap-2 border-t border-line pt-4 text-xs text-fg-subtle">
            <FileText className="size-3.5 shrink-0" /> Exports contain text and keyframe references only. Raw video stays on the box.
          </p>
        </Panel>
      </aside>
    </div>
  )
}
