import { chromium } from '@playwright/test'
const S = process.argv[2], base = process.argv[3] ?? 'http://127.0.0.1:5719'
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', `--use-file-for-fake-video-capture=${process.cwd()}/e2e/.media/capture.mjpeg`, `--use-file-for-fake-audio-capture=${process.cwd()}/e2e/.media/answer.wav`, '--autoplay-policy=no-user-gesture-required'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto(base + '/studio' + (base.includes('5719') ? '' : '?title=' + encodeURIComponent('QA studio run (tacit-web)')), { waitUntil: 'networkidle' })
await page.getByTestId('capture-start').click()
await page.waitForTimeout(Number(process.env.LIVE_MS ?? 13000))
await page.screenshot({ path: `${S}/studio-live.png` })
const steps = await page.locator('[data-testid="step-timeline"] [title]').count().catch(() => 0)
const questions = await page.getByTestId('coach-question').count()
const answers = await page.getByTestId('expert-answer').count()
const events = await page.locator('text=/^(grasp|release|move|look|pause)$/').count()
console.log(JSON.stringify({ steps, questions, answers, events, hud: await page.getByTestId('latency-hud').innerText() }).slice(0, 600))
const t0 = Date.now()
await page.getByTestId('capture-stop').click()
await page.getByTestId('processing-panel').waitFor({ timeout: 90000 }).then(() => console.log('stop -> processing view', ((Date.now() - t0) / 1000).toFixed(1), 's')).catch(() => console.log('no processing view within 90 s'))
await page.waitForTimeout(3000)
await page.screenshot({ path: `${S}/studio-processing.png` })
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no console errors')
await browser.close()
